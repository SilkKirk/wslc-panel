//! 数据库域（`impl Shell`）：按**能力**分文件，和 `views/db_*` 一一对得上。
//!
//! 原先是一份 2693 行的 `db.rs`（47 个方法、5 件事）：找"备份怎么删的"
//! 得先翻过连接、库表、SQL 控制台三摊。拆法：
//!
//! | 文件 | 覆盖 |
//! |---|---|
//! | [`conn`] | 连接表单与凭据来源（连接卡 / 面板记的账号 / 连接串） |
//! | [`page`] | 「数据库管理」页的生命周期（探测 / 读表 / 切 tab / 离开） |
//! | [`dialog`] | 一次性动作弹窗（建库 / 建用户 / 改密 / 授权 / 导入 SQL） |
//! | [`console`] | SQL 控制台（执行、多结果、原始输出、导出 CSV） |
//! | [`tree`] | 控制台左侧的库 / 表树（官方 `Tree`） |
//! | [`backup`] | 备份 / 恢复 / 删备份 |
//!
//! 这些都是 `Shell` 的**后代模块**（`app/shell/db/mod.rs`），所以照样能读
//! `Shell` 的私有字段 —— 见 `app/shell/mod.rs` 里"结构体必须留在这一层"。

