//! `state` 的单测（116 条）：**一个域一个文件**。
//!
//! # 为什么拆
//!
//! 原先是一整份 2720 行的 `tests.rs`，10 个域的断言按"写的时候的顺序"排在一起 ——
//! 改 `db_state.rs` 时得在一份跨域文件里翻到对应那一段，改完还得确认没碰错别的域。
//! 而 `AGENTS.md` §2 的规则明明是"一个域一个文件、`impl` 跟着它修饰的类型走"：
//! 测试是这条规则的**反面教材**。
//!
//! # 目录
//!
//! | 文件 | 覆盖 |
//! |---|---|
//! | [`actions`] | 危险动作 / 提示输入的文案与副作用、二次确认的分派 |
//! | [`app`] | `AppState` 的初值、刷新间隔、`ui_sections`、提示条、会话标签 |
//! | [`db`] | 数据库域：连接串、库表用户、备份与导入、错误分类 |
//! | [`deploy`] | 部署域：运行时识别、阶段文案、失败建议 |
//! | [`install`] | 安装域：来源能力、计划、进度事件、在线清单与镜像测速 |
//! | [`logs`] | 日志 / 拉取进度的中间状态 |
//! | [`nav`] | 页面枚举、分组、侧边栏高亮、谁能直接进 |
//! | [`registry`] | 镜像仓库查询状态与 tag 选择 |
//! | [`snapshot`] | 快照派生的数字（总览 / 镜像体积合计 / 存储环） |
//! | [`wslconf`] | `/etc/wsl.conf` 编辑器的字段 id、分节展开与保存 |
//!
//! 拆分是**纯搬迁**：断言一条没改（`core` job 的测试条数就是判据）。
//! 新测试按**它测哪个域**放进对应文件 —— 不要因为"顺手"再堆回一个公共文件。

mod actions;
mod app;
mod db;
mod deploy;
mod install;
mod logs;
mod nav;
mod registry;
mod snapshot;
mod wslconf;
